"""
ToolSense - Combined model: Tool wear prediction + RUL + accuracy metrics

Pipeline
  1. Wear model   : Ridge + Random Forest hybrid, 5-cut smoothing, running max
  2. RUL method A : rate method        (threshold - wear) / wear rate over last N cuts
  3. RUL method B : calibrated method  (wear -> remaining cuts curve from training cutters)
  4. Metrics      : wear (MAE, RMSE, R2, MAPE/accuracy) + RUL (MAE, RMSE, R2, within +-N cuts)
  5. Outputs      : toolsense_model.joblib, toolsense_results_c6.csv, toolsense_report.png

Run:  python toolsense_combined.py
Needs c1/c4/c6_aggregated_features.csv in the same folder.
"""
import numpy as np
import pandas as pd
import joblib
from sklearn.ensemble import RandomForestRegressor
from sklearn.feature_selection import SelectKBest, f_regression
from sklearn.isotonic import IsotonicRegression
from sklearn.linear_model import Ridge
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import (mean_absolute_error, root_mean_squared_error,
                             r2_score, mean_absolute_percentage_error)

# ------------------------------------------------------------------ settings
TRAIN_FILES = ["c1_aggregated_features.csv", "c4_aggregated_features.csv"]
TEST_FILE = "c6_aggregated_features.csv"          # unseen cutter for the demo
ALL_FILES = TRAIN_FILES + [TEST_FILE]
FLUTE_COLS = ["flute_1", "flute_2", "flute_3"]
IGNORE_COLS = ["cut_number", "max_wear", "cutter"] + FLUTE_COLS

SMOOTH_WINDOW = 5
FAILURE_THRESHOLD = 180.0   # micrometres - ASSUMPTION, set from a cited wear limit
MIN_HISTORY = 5
MIN_RATE = 0.01             # um/cut; below this wear is "flat", rate method gives no RUL
MAX_RUL = 400               # cap so a flat wear curve can't give absurd values
WARMUP = 30                 # RUL evaluated only after this many cuts
RUL_TOLERANCE = 20          # "accurate" if RUL error is within +-20 cuts
RUN_LOCO = True             # leave-one-cutter-out validation on c1, c4, c6


# ------------------------------------------------------------------ 1. wear model
def train_models(df_train):
    feature_cols = [c for c in df_train.columns if c not in IGNORE_COLS]
    X = df_train[feature_cols]
    y_flutes = df_train[FLUTE_COLS].to_numpy()
    y_max = (df_train["max_wear"].to_numpy()
             if "max_wear" in df_train.columns else y_flutes.max(axis=1))

    selector = SelectKBest(f_regression, k=30).fit(X, y_max)
    top_features = [feature_cols[i] for i in selector.get_support(indices=True)]

    scaler = StandardScaler().fit(X[top_features])
    ridge = Ridge(alpha=50.0).fit(scaler.transform(X[top_features]), y_flutes)

    rf = RandomForestRegressor(n_estimators=300, min_samples_leaf=2,
                               max_features=0.3, random_state=42, n_jobs=-1)
    rf.fit(X, y_flutes)

    return {"feature_cols": feature_cols, "top_features": top_features,
            "scaler": scaler, "ridge": ridge, "rf": rf}


class WearPredictor:
    """Predicts wear one cut at a time (live/streaming). One instance per tool run."""

    def __init__(self, artifacts, smooth_window=SMOOTH_WINDOW):
        self.a = artifacts
        self.smooth_window = smooth_window
        self.raw_history = []
        self.running = None
        self.max_wear_history = []

    def predict_cut(self, features):
        x = pd.DataFrame([features]) if isinstance(features, dict) else features
        x = x[self.a["feature_cols"]]
        p_ridge = self.a["ridge"].predict(
            self.a["scaler"].transform(x[self.a["top_features"]]))[0]
        p_rf = self.a["rf"].predict(x)[0]
        raw = 0.5 * p_ridge + 0.5 * p_rf

        self.raw_history.append(raw)
        smooth = np.mean(self.raw_history[-self.smooth_window:], axis=0)
        self.running = smooth if self.running is None else np.maximum(self.running, smooth)

        max_wear = float(self.running.max())
        self.max_wear_history.append(max_wear)
        return {"cut": len(self.raw_history),
                "flutes": [float(v) for v in self.running],
                "max_wear": max_wear}


def stream_wear(artifacts, df):
    """Replay a cutter cut by cut. Returns (flute predictions [n,3], max wear [n])."""
    p = WearPredictor(artifacts)
    flutes, maxw = [], []
    for i in range(len(df)):
        out = p.predict_cut(df.iloc[[i]][artifacts["feature_cols"]])
        flutes.append(out["flutes"])
        maxw.append(out["max_wear"])
    return np.array(flutes), np.array(maxw)


def wear_metrics(df_true, pred_flutes, pred_max):
    y_f = df_true[FLUTE_COLS].to_numpy()
    y_m = df_true["max_wear"].to_numpy()
    mape = mean_absolute_percentage_error(y_m, pred_max) * 100
    return {
        "flutes_mae": mean_absolute_error(y_f, pred_flutes),
        "flutes_rmse": root_mean_squared_error(y_f, pred_flutes),
        "flutes_r2": r2_score(y_f, pred_flutes),
        "max_mae": mean_absolute_error(y_m, pred_max),
        "max_rmse": root_mean_squared_error(y_m, pred_max),
        "max_r2": r2_score(y_m, pred_max),
        "max_mape": mape,
        "max_accuracy": 100.0 - mape,
    }


# ------------------------------------------------------------------ 2. RUL method A (rate)
def calculate_rul(wear_history, threshold=FAILURE_THRESHOLD, window=30,
                  min_history=MIN_HISTORY, min_rate=MIN_RATE, max_rul=MAX_RUL):
    n = len(wear_history)
    current = wear_history[-1]
    if current >= threshold:
        return 0
    used = min(window, n - 1)
    if used < min_history:
        return None
    rate = (current - wear_history[-1 - used]) / used
    if rate <= min_rate:
        return None
    return min(int(round((threshold - current) / rate)), max_rul)


# ------------------------------------------------------------------ 3. RUL method B (calibrated)
def build_wear_to_rul_curve(true_wear_curves, threshold=FAILURE_THRESHOLD):
    wear_pts, rul_pts = [], []
    for w in true_wear_curves:
        crossed = np.where(np.asarray(w) >= threshold)[0]
        if len(crossed) == 0:
            continue
        T = int(crossed[0])
        for t in range(T):
            wear_pts.append(w[t])
            rul_pts.append(T - t)
    if len(set(wear_pts)) < 2:
        return None
    return IsotonicRegression(increasing=False, out_of_bounds="clip").fit(wear_pts, rul_pts)


def calibrated_rul(current_wear, curve, threshold=FAILURE_THRESHOLD):
    if curve is None:
        return None
    if current_wear >= threshold:
        return 0
    return int(round(float(curve.predict([current_wear])[0])))


def get_recommendation(current_wear, threshold=FAILURE_THRESHOLD):
    ratio = current_wear / threshold
    if ratio < 0.6:
        return "continue"
    if ratio < 0.85:
        return "reduce_feed"
    return "replace_tool"


# ------------------------------------------------------------------ 4. RUL backtest + metrics
def rul_backtest(pred_wear, true_wear, rul_fn, threshold=FAILURE_THRESHOLD, warmup=WARMUP):
    """True RUL = cuts until REAL wear first crosses the threshold."""
    crossed = np.where(np.asarray(true_wear) >= threshold)[0]
    if len(crossed) == 0:
        return None
    T = int(crossed[0])
    rows = []
    for t in range(warmup, T):
        r = rul_fn(pred_wear[:t + 1])
        if r is not None:
            rows.append((t + 1, T - t, r))
    if not rows:
        return None
    df = pd.DataFrame(rows, columns=["cut", "true_rul", "pred_rul"])
    df["abs_error"] = (df["pred_rul"] - df["true_rul"]).abs()
    near_end = df[df["true_rul"] <= 50]
    return {
        "T": T + 1, "n": len(df), "df": df,
        "mae": df["abs_error"].mean(),
        "rmse": float(np.sqrt(((df["pred_rul"] - df["true_rul"]) ** 2).mean())),
        "r2": r2_score(df["true_rul"], df["pred_rul"]) if len(df) > 1 else float("nan"),
        "mae_last50": near_end["abs_error"].mean() if len(near_end) else float("nan"),
        "within_tol": (df["abs_error"] <= RUL_TOLERANCE).mean() * 100,
    }


def print_wear_metrics(m, title):
    print(f"\n----- {title} -----")
    print(f"Flutes   MAE {m['flutes_mae']:.2f} um | RMSE {m['flutes_rmse']:.2f} um | R2 {m['flutes_r2']:.4f}")
    print(f"Max wear MAE {m['max_mae']:.2f} um | RMSE {m['max_rmse']:.2f} um | R2 {m['max_r2']:.4f}")
    print(f"Max wear MAPE {m['max_mape']:.2f}% | Accuracy (100 - MAPE) {m['max_accuracy']:.2f}%")


# ------------------------------------------------------------------ main
if __name__ == "__main__":
    data = {f: pd.read_csv(f).sort_values("cut_number").reset_index(drop=True) for f in ALL_FILES}

    rul_methods = {
        "A rate (last 30 cuts)": lambda h, c: calculate_rul(h, window=30),
        "A rate (last 60 cuts)": lambda h, c: calculate_rul(h, window=60),
        "B calibrated (lookup)": lambda h, c: calibrated_rul(h[-1], c),
    }

    # ---------- leave-one-cutter-out validation (more reliable than a single test cutter)
    folds = {}
    holdouts = ALL_FILES if RUN_LOCO else [TEST_FILE]
    for held in holdouts:
        others = [f for f in ALL_FILES if f != held]
        art = train_models(pd.concat([data[f] for f in others], ignore_index=True))
        pf, pm = stream_wear(art, data[held])
        curve = build_wear_to_rul_curve([data[f]["max_wear"].to_numpy() for f in others])
        folds[held] = {"art": art, "pred_flutes": pf, "pred_max": pm,
                       "true_max": data[held]["max_wear"].to_numpy(), "curve": curve}

    print("=" * 70)
    print("WEAR PREDICTION - accuracy per held-out cutter")
    print("=" * 70)
    for held, f in folds.items():
        m = wear_metrics(data[held], f["pred_flutes"], f["pred_max"])
        tag = "  <-- demo cutter (unseen)" if held == TEST_FILE else ""
        print_wear_metrics(m, f"held out {held[:2]}{tag}")

    print("\n" + "=" * 70)
    print(f"RUL - accuracy (threshold {FAILURE_THRESHOLD:.0f} um, evaluated after {WARMUP} cuts)")
    print(f"Errors in cuts. 'within' = % of predictions with error <= {RUL_TOLERANCE} cuts")
    print("=" * 70)
    summary = {m: [] for m in rul_methods}
    demo_rul = {}
    for held, f in folds.items():
        print(f"\nCutter {held[:2]}")
        for name, fn in rul_methods.items():
            res = rul_backtest(f["pred_max"], f["true_max"], lambda h, fn=fn, f=f: fn(h, f["curve"]))
            if res is None:
                print(f"  {name:24s} no result (never reaches threshold / no trend)")
                continue
            summary[name].append(res)
            if held == TEST_FILE:
                demo_rul[name] = res["df"]
            print(f"  {name:24s} MAE {res['mae']:6.1f} | RMSE {res['rmse']:6.1f} | R2 {res['r2']:6.3f} | "
                  f"MAE(last 50) {res['mae_last50']:6.1f} | within {res['within_tol']:5.1f}% "
                  f"(true crossing at cut {res['T']})")

    if RUN_LOCO:
        print("\nAverage over held-out cutters:")
        for name, rs in summary.items():
            if rs:
                print(f"  {name:24s} MAE {np.nanmean([r['mae'] for r in rs]):6.1f} | "
                      f"RMSE {np.nanmean([r['rmse'] for r in rs]):6.1f} | "
                      f"MAE(last 50) {np.nanmean([r['mae_last50'] for r in rs]):6.1f} | "
                      f"within {np.nanmean([r['within_tol'] for r in rs]):5.1f}%")

    # ---------- deployment model = trained on c1 + c4, c6 unseen
    demo = folds[TEST_FILE] if TEST_FILE in folds else None
    deploy = dict(demo["art"])
    deploy["rul_curve"] = demo["curve"]
    joblib.dump(deploy, "toolsense_model.joblib")
    print("\nSaved toolsense_model.joblib (trained on c1 + c4)")

    # ---------- combined per-cut output for the demo cutter: wear + RUL + recommendation
    df6 = data[TEST_FILE]
    pm = demo["pred_max"]
    rows = []
    for i in range(len(df6)):
        hist = pm[:i + 1]
        rows.append({
            "cut_number": int(df6["cut_number"].iloc[i]),
            "pred_flute_1": demo["pred_flutes"][i, 0],
            "pred_flute_2": demo["pred_flutes"][i, 1],
            "pred_flute_3": demo["pred_flutes"][i, 2],
            "pred_max_wear": pm[i],
            "true_max_wear": df6["max_wear"].iloc[i],
            "rul_rate_A": calculate_rul(hist, window=30) if i + 1 >= WARMUP else None,
            "rul_calibrated_B": calibrated_rul(pm[i], demo["curve"]) if i + 1 >= WARMUP else None,
            "recommendation": get_recommendation(pm[i]),
        })
    out = pd.DataFrame(rows)
    out.to_csv("toolsense_results_c6.csv", index=False)
    print("\nSaved toolsense_results_c6.csv - sample (every 30th cut):")
    print(out.iloc[::30].round(1).to_string(index=False))

    # ---------- plots
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(1, 2, figsize=(13, 4.5))
        ax[0].plot(df6["cut_number"], df6["max_wear"], "k", lw=2, label="True max wear")
        ax[0].plot(df6["cut_number"], pm, "tab:blue", label="Predicted max wear")
        ax[0].axhline(FAILURE_THRESHOLD, color="r", ls="--", label=f"Threshold {FAILURE_THRESHOLD:.0f} um")
        ax[0].set_xlabel("Cut number"); ax[0].set_ylabel("Wear (um)")
        ax[0].set_title("Wear prediction on unseen cutter c6"); ax[0].legend(fontsize=8)

        first = next(iter(demo_rul.values()), None)
        if first is not None:
            ax[1].plot(first["cut"], first["true_rul"], "k", lw=2, label="True RUL")
        for name, d in demo_rul.items():
            ax[1].plot(d["cut"], d["pred_rul"], label=name)
        ax[1].set_xlabel("Cut number"); ax[1].set_ylabel("Remaining cuts")
        ax[1].set_title("RUL backtest on unseen cutter c6"); ax[1].legend(fontsize=8)
        plt.tight_layout(); plt.savefig("toolsense_report.png", dpi=150)
        print("\nSaved toolsense_report.png")
    except ImportError:
        pass